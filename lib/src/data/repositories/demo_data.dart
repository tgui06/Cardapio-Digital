String demoArea(int mesa) => mesa <= 10 ? 'Salão' : (mesa <= 14 ? 'Varanda' : 'Balcão');

/// Cada garçom cuida de uma área (recebe os chamados dessas mesas).
(int, String) demoGarcom(int mesa) => mesa <= 10 ? (1, 'Carla') : (mesa <= 14 ? (2, 'Diego') : (3, 'Bruna'));

List<Map<String, dynamic>> demoMesasJson(DateTime now) {
  String ago(int min) => now.subtract(Duration(minutes: min)).toIso8601String();
  return [
    for (var n = 1; n <= 16; n++)
      {
        'numero': n,
        'lugares': n > 14 ? 2 : (n % 3 == 0 ? 6 : 4),
        'area': demoArea(n),
        'garcom_nome': demoGarcom(n).$2,
        'status': switch (n) {
          2 || 5 || 9 || 12 => 'ocupada',
          7 || 13 => 'conta',
          _ => 'livre',
        },
        'total_consumido': switch (n) {
          2 => 86.7,
          5 => 154.3,
          9 => 42.8,
          12 => 211.5,
          7 => 318.9,
          13 => 97.6,
          _ => 0,
        },
        'aberta_em': switch (n) {
          2 => ago(25),
          5 => ago(52),
          9 => ago(8),
          12 => ago(71),
          7 => ago(95),
          13 => ago(64),
          _ => null,
        },
      },
  ];
}
